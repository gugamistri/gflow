export function normalizeLocaleTag(tag) {
  const raw = String(tag || "").trim().toLowerCase().replace(/_/g, "-");
  if (!raw) return null;
  const primary = raw.split("-")[0];
  if (primary === "pt") return "pt";
  if (primary === "es") return "es";
  if (primary === "en") return "en";
  return null;
}

/** @param {string[]|string|undefined|null} languages */
export function resolveLocale(languages) {
  const list = Array.isArray(languages)
    ? languages
    : typeof languages === "string"
      ? [languages]
      : [];
  for (const tag of list) {
    const hit = normalizeLocaleTag(tag);
    if (hit) return hit;
  }
  return "en";
}

function readStoredLocale() {
  try {
    const raw = localStorage.getItem(LOCALE_STORAGE_KEY);
    return normalizeLocaleTag(raw);
  } catch {
    return null;
  }
}

function browserLanguages() {
  if (typeof navigator === "undefined") return [];
  if (Array.isArray(navigator.languages) && navigator.languages.length) {
    return [...navigator.languages];
  }
  return navigator.language ? [navigator.language] : [];
}

export function detectLocale() {
  return readStoredLocale() || resolveLocale(browserLanguages());
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale, { persist = true } = {}) {
  const next = normalizeLocaleTag(locale) || "en";
  currentLocale = next;
  if (persist) {
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = HTML_LANG[next] || next;
  }
  return next;
}

/** Idioma fixo da página (/en, /es): vem no HTML pré-renderizado e vence a preferência salva. */
function pageLocale() {
  if (typeof document === "undefined") return null;
  return normalizeLocaleTag(document.documentElement.getAttribute("data-page-locale"));
}

/** URL da mesma página no idioma pedido (data-alt-pt|en|es no <html> das páginas públicas). */
export function localizedPageUrl(locale) {
  if (typeof document === "undefined") return null;
  return document.documentElement.getAttribute(`data-alt-${locale}`) || null;
}

/** Seletor de idioma com links reais: o clique também guarda a preferência (a navegação segue normal). */
function bindLocaleLinks() {
  if (typeof document === "undefined" || !document.addEventListener) return;
  document.addEventListener("click", (e) => {
    const a = e.target?.closest?.(".locale-links a[hreflang]");
    const next = a && normalizeLocaleTag(a.getAttribute("lang") || a.getAttribute("hreflang"));
    if (!next) return;
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, next);
    } catch {
      /* ignore */
    }
  });
}

export function initLocale() {
  bindLocaleLinks();
  const fixed = pageLocale();
  if (fixed) return setLocale(fixed, { persist: false });
  return setLocale(detectLocale(), { persist: Boolean(readStoredLocale()) });
}

export function t(key, vars) {
  const cat = catalogs[currentLocale] || catalogs.en;
  let text = cat[key] ?? catalogs.en[key] ?? catalogs.pt[key] ?? String(key);
  if (vars && typeof vars === "object") {
    text = text.replace(/\{(\w+)\}/g, (_, name) =>
      vars[name] != null ? String(vars[name]) : `{${name}}`
    );
  }
  return text;
}

export function themePresetName(id, fallback) {
  const key = `theme.preset.${id}`;
  const cat = catalogs[currentLocale] || catalogs.en;
  if (cat[key] || catalogs.en[key] || catalogs.pt[key]) return t(key);
  return fallback || id;
}

const ATTR_MAP = [
  ["data-i18n", null],
  ["data-i18n-html", "html"],
  ["data-i18n-title", "title"],
  ["data-i18n-aria", "aria-label"],
  ["data-i18n-placeholder", "placeholder"],
  ["data-i18n-alt", "alt"],
];

function applyNode(el, attr, mode) {
  const key = el.getAttribute(attr);
  if (!key) return;
  const value = t(key);
  if (mode === "html") el.innerHTML = value;
  else if (mode === "title") el.setAttribute("title", value);
  else if (mode === "aria-label") el.setAttribute("aria-label", value);
  else if (mode === "placeholder") el.setAttribute("placeholder", value);
  else if (mode === "alt") el.setAttribute("alt", value);
  else el.textContent = value;
}

/** @param {ParentNode} [root] */
export function applyI18n(root) {
  const scope = root || (typeof document !== "undefined" ? document : null);
  if (!scope || !scope.querySelectorAll) return;
  for (const [attr, mode] of ATTR_MAP) {
    const nodes = scope.querySelectorAll(`[${attr}]`);
    for (const el of nodes) applyNode(el, attr, mode);
  }
  const titleEl = typeof document !== "undefined" ? document.querySelector("title[data-i18n]") : null;
  if (titleEl) titleEl.textContent = t(titleEl.getAttribute("data-i18n"));
}

/** Menu de idioma das páginas públicas (<details class="locale-menu">): Esc e clique fora fecham. */
if (typeof document !== "undefined" && typeof document.addEventListener === "function") {
  document.addEventListener("keydown", (e) => {
    if (e.key !== "Escape") return;
    const open = document.querySelector("details.locale-menu[open]");
    if (!open) return;
    open.open = false;
    open.querySelector("summary")?.focus();
  });
  document.addEventListener("click", (e) => {
    for (const d of document.querySelectorAll("details.locale-menu[open]")) if (!d.contains(e.target)) d.open = false;
  });
}

export function bindLocaleSelect(selectEl, onChange) {
  if (!selectEl) return;
  selectEl.value = getLocale();
  selectEl.addEventListener("change", () => {
    setLocale(selectEl.value);
    // why: cada idioma tem a própria URL — a escolha do usuário leva à página certa (sem redirect automático)
    const href = localizedPageUrl(getLocale());
    if (href && typeof location !== "undefined" && href !== location.pathname) {
      location.assign(href + (location.hash || ""));
      return;
    }
    applyI18n(document);
    if (typeof onChange === "function") onChange(getLocale());
    try {
      window.dispatchEvent(new CustomEvent("ns-locale-change", { detail: { locale: getLocale() } }));
    } catch {
      /* ignore */
    }
  });
}

